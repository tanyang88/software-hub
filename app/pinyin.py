def key(text):
    """把名称转成拼音排序键：汉字 -> 无声调拼音，ASCII -> 小写，其余原样保留。"""
    parts = []
    for ch in text or "":
        if ch.isascii():
            parts.append(ch.lower())
        elif ch in _OVERRIDES:
            parts.append(_OVERRIDES[ch])
        elif ch in _TABLE:
            parts.append(_TABLE[ch])
        else:
            parts.append(ch)
    return "".join(parts)
